# Generates DelphiDoom.OpenGl.Recorder.Thunks.pas: one recording thunk for every gl*/glu* function that the
# OpenGL renderer (Libs\OpenGl\Legacy) uses and that dglOpenGL.pas declares as a procedure variable.
#
#   .\Libs\OpenGl\Recorder\Genera-Thunks.ps1
#
# The list of functions is not written by hand: it is every identifier gl[A-Z]... / glu[A-Z]... found in the
# unit of Libs\OpenGl\Legacy that has BOTH a type  TglXxx = procedure|function(...)  and a variable
#   glXxx: TglXxx;   in Libs\OpenGl\Binding\dglOpenGL.pas. wgl* (context) functions are not recorded.
# Run it again after a function is added to (or taken away from) the renderer, and commit the result.
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path
$binding = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'Libs\OpenGl\Binding\dglOpenGL.pas')
$legacy = ''
Get-ChildItem (Join-Path $root 'Libs\OpenGl\Legacy') -Filter *.pas | ForEach-Object { $legacy += (Get-Content -Raw $_.FullName) + "`n" }

$names = [regex]::Matches($legacy, '\b(glu?[A-Z][A-Za-z0-9]*)\b') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique

$typeRx = '(?m)^\s*Tgl_NAME_\s*=\s*(procedure|function)\s*(\((?<p>[^)]*)\))?\s*(:\s*(?<r>\w+))?\s*;'
$functions = @()
$unsupported = @()
foreach ($name in $names) {
  $varRx = "(?m)^\s*$name\s*:\s*T$name\s*;"
  if ($binding -notmatch $varRx) { continue }
  $rx = $typeRx.Replace('gl_NAME_', $name)
  $m = [regex]::Match($binding, $rx)
  if (-not $m.Success) { $unsupported += $name; continue }
  $params = @()
  $text = $m.Groups['p'].Value
  if ($text.Trim() -ne '') {
    foreach ($group in ($text -split ';')) {
      $g = $group.Trim()
      if ($g -eq '') { continue }
      $mode = ''
      if ($g -match '^(const|var|out)\s+') { $mode = $Matches[1]; $g = $g.Substring($Matches[0].Length) }
      $parts = $g -split ':'
      if ($parts.Count -ne 2) { $unsupported += "$name($g)"; continue }
      $type = $parts[1].Trim()
      foreach ($pn in ($parts[0] -split ',')) {
        $params += [pscustomobject]@{ Name = $pn.Trim(); Type = $type; Mode = $mode }
      }
    }
  }
  $functions += [pscustomobject]@{ Name = $name; Kind = $m.Groups[1].Value; Params = $params; Result = $m.Groups['r'].Value }
}

function Get-ValueKind([string]$type, [string]$mode) {
  if ($mode -eq 'var' -or $mode -eq 'out') { return 'Pointer' }
  switch -Regex ($type) {
    '^GLenum$' { return 'Enum' }
    '^(GLfloat|GLclampf|Single)$' { return 'Single' }
    '^(GLdouble|GLclampd|Double)$' { return 'Double' }
    '^(GLint|GLuint|GLsizei|GLbitfield|GLboolean|GLubyte|GLbyte|GLshort|GLushort|Integer|Cardinal|Boolean|Byte|GLintptr|GLsizeiptr|GLint64|GLuint64)$' { return 'Integer' }
    '^(P\w+|Pointer|PAnsiChar|PChar)$' { return 'Pointer' }
    default { return $null }
  }
}

$bad = @()
foreach ($f in $functions) {
  foreach ($p in $f.Params) {
    if (-not (Get-ValueKind $p.Type $p.Mode)) { $bad += "$($f.Name): $($p.Name): $($p.Type)" }
  }
}
if ($bad.Count -gt 0 -or $unsupported.Count -gt 0) {
  $bad | ForEach-Object { Write-Host "TIPO NON GESTITO $_" }
  $unsupported | ForEach-Object { Write-Host "DICHIARAZIONE NON GESTITA $_" }
  throw 'Il generatore non conosce alcuni tipi: aggiungili a Get-ValueKind'
}

$sb = New-Object System.Text.StringBuilder
function Add([string]$line) { [void]$sb.Append($line).Append("`r`n") }

Add '{******************************************************************************}'
Add '{                                                                              }'
Add '{  DelphiDoom: OpenGL call recorder - the recording thunks (GENERATED)         }'
Add '{                                                                              }'
Add '{  Generated by Libs\OpenGl\Recorder\Genera-Thunks.ps1: do not edit by hand.   }'
Add '{  Licensed under the GNU General Public License, version 2 or later           }'
Add '{                                                                              }'
Add '{******************************************************************************}'
Add '// One thunk for every gl/glu function of dglOpenGL.pas that the renderer uses. A thunk has the'
Add '// signature of the function it replaces: it writes the call into the recording session and then'
Add '// calls the original. The unit is compiled only into a test executable (see Hook.pas).'
Add 'unit DelphiDoom.OpenGl.Recorder.Thunks;'
Add ''
Add 'interface'
Add ''
Add 'uses'
Add '  DelphiDoom.OpenGl.Recorder.Intf;'
Add ''
Add '/// <summary>The table of the recorded functions: the variables of dglOpenGL and their thunks</summary>'
Add 'function CreateGlHookTable: IGlHookTable;'
Add ''
Add 'implementation'
Add ''
Add 'uses'
Add '  dglOpenGL,'
Add '  DelphiDoom.OpenGl.Recorder.Types,'
Add '  DelphiDoom.OpenGl.Recorder.Session,'
Add '  DelphiDoom.OpenGl.Recorder.HookTable;'
Add ''
Add 'const'
Add "  FUNCTION_COUNT = $($functions.Count);"
Add ''
Add 'var'
Add '  GOriginals: array[0..FUNCTION_COUNT - 1] of Pointer;'
Add ''

$index = 0
foreach ($f in $functions) {
  $sig = ($f.Params | ForEach-Object {
      $prefix = ''
      if ($_.Mode -ne '') { $prefix = $_.Mode + ' ' }
      "$prefix$($_.Name): $($_.Type)"
    }) -join '; '
  $values = ($f.Params | ForEach-Object {
      $kind = Get-ValueKind $_.Type $_.Mode
      $n = $_.Name
      if ($_.Mode -eq 'var' -or $_.Mode -eq 'out') { $n = "@$n" }
      switch ($kind) {
        'Enum' { "TGlValue.FromEnum($n)" }
        'Integer' { "TGlValue.FromInteger(Int64($n))" }
        'Single' { "TGlValue.FromSingle($n)" }
        'Double' { "TGlValue.FromDouble($n)" }
        'Pointer' { "TGlValue.FromPointer(Pointer($n))" }
      }
    }) -join ', '
  $args = ($f.Params | ForEach-Object { $_.Name }) -join ', '
  $head = "Hook_$($f.Name)"
  if ($sig -ne '') { $head += "($sig)" }
  if ($f.Kind -eq 'function') { $head = "function $head`: $($f.Result)" } else { $head = "procedure $head" }
  Add "$head; stdcall;"
  Add 'begin'
  Add "  GlSessionRecord('$($f.Name)', [$values]);"
  $call = "T$($f.Name)(GOriginals[$index])"
  if ($args -ne '') { $call += "($args)" }
  if ($f.Kind -eq 'function') { Add "  Result := $call;" } else { Add "  $call;" }
  Add 'end;'
  Add ''
  $index++
}

Add 'function CreateGlHookTable: IGlHookTable;'
Add 'var'
Add '  LTable: TGlHookTable;'
Add 'begin'
Add '  LTable := TGlHookTable.Create(@GOriginals[0]);'
foreach ($f in $functions) {
  Add "  LTable.Add('$($f.Name)', @@$($f.Name), @Hook_$($f.Name));"
}
Add '  Result := LTable;'
Add 'end;'
Add ''
Add 'end.'

$out = Join-Path $PSScriptRoot 'DelphiDoom.OpenGl.Recorder.Thunks.pas'
[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))
Write-Host "Scritte $($functions.Count) funzioni in $out"
