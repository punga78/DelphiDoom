# GenerateKeenTables.pl - writes the Pascal tables of Libs\Keen from the C sources of Keen Dreams
# (Reference\keen, id Software, GPL v2 or later): the constants of graphkdr.h and audiokdr.h, the ids of the
# think, contact and react functions, and the 213 statetype of kd_keen.c, kd_act1.c and kd_act2.c.
#
# Usage:  perl Tools\Keen\GenerateKeenTables.pl <folder of the C sources> <output folder>
# The output is written once and kept in the repository (the C sources are not in it): run this again only
# if the generator changes.
use strict;
use warnings;

my ($src, $out) = @ARGV;
die "usage: GenerateKeenTables.pl <C sources> <output folder>\n" unless $src && $out;

sub slurp {
  my ($name) = @_;
  open(my $f, '<', "$src/$name") or die "$name: $!";
  local $/;
  my $t = <$f>;
  close $f;
  return $t;
}

sub write_unit {
  my ($name, $text) = @_;
  $text =~ s/\r?\n/\r\n/g;
  open(my $f, '>:raw', "$out/$name") or die "$name: $!";
  print $f $text;
  close $f;
}

my $header = <<'HDR';
{******************************************************************************}
{                                                                              }
{  DelphiDoom: keen library - %s
{  Port of Commander Keen in Keen Dreams (id Software), GPL v2 or later         }
{  Generated by Tools\Keen\GenerateKeenTables.pl from the C sources: do not edit }
{                                                                              }
{  Licensed under the GNU General Public License, version 2 or later           }
{                                                                              }
{******************************************************************************}
HDR

sub head {
  my ($title) = @_;
  my $line = sprintf($header, sprintf("%-52s}", $title));
  return $line;
}

# ---- constants of graphkdr.h and audiokdr.h ----

sub constants {
  my ($file, $prefix) = @_;
  my $t = slurp($file);
  my @lines;
  while ($t =~ /^#define\s+(\w+)\s+(\d+)\s*$/mg) {
    push @lines, sprintf("  %s%s = %d;", $prefix, $1, $2);
  }
  return @lines;
}

my @gfx = constants('graphkdr.h', 'KEEN_GFX_');
my @snd = constants('audiokdr.h', 'KEEN_SND_');

write_unit('DelphiDoom.Keen.GraphicsIds.pas',
  head('the numbers of the graphics chunks (graphkdr.h)') .
  "unit DelphiDoom.Keen.GraphicsIds;\n\ninterface\n\nconst\n" . join("\n", @gfx) . "\n\nimplementation\n\nend.\n");
write_unit('DelphiDoom.Keen.AudioIds.pas',
  head('the numbers of the sounds (audiokdr.h)') .
  "unit DelphiDoom.Keen.AudioIds;\n\ninterface\n\nconst\n" . join("\n", @snd) . "\n\nimplementation\n\nend.\n");

# ---- the statetype of the three game files ----

my %gfxname;
$gfxname{$_} = 1 for map { /KEEN_GFX_(\w+)/ ? $1 : () } @gfx;

my @states;      # [name, fields]
my %stateindex;
my %actions;     # function name -> 1
for my $file ('kd_keen.c', 'kd_act1.c', 'kd_act2.c') {
  my $t = slurp($file);
  # remove the comments so that a statetype in one does not count
  $t =~ s{/\*.*?\*/}{}gs;
  $t =~ s{//[^\n]*}{}g;
  while ($t =~ /\bstatetype\s+(s_\w+)\s*=\s*\{(.*?)\}\s*;/gs) {
    my ($name, $body) = ($1, $2);
    $body =~ s/\s+/ /g;
    my @f = split /\s*,\s*/, $body;
    @f = map { s/^\s+|\s+$//gr } @f;
    die "$name has " . scalar(@f) . " fields: $body\n" unless @f == 12;
    $stateindex{$name} = scalar(@states);
    push @states, [$name, @f];
    for my $i (8, 9, 10) {
      $actions{$f[$i]} = 1 if $f[$i] ne 'NULL';
    }
  }
}
die "expected 213 states, found " . scalar(@states) . "\n" unless @states == 213;

my @actionnames = sort keys %actions;
my %actionid;
my $n = 1;
$actionid{$_} = $n++ for @actionnames;

# the ids of the actions
my @act;
push @act, "  KEEN_ACTION_NONE = 0;";
push @act, sprintf("  KEEN_ACTION_%s = %d;", uc($_), $actionid{$_}) for @actionnames;
my @actnames;
push @actnames, "    ''";
push @actnames, sprintf("    '%s'", $_) for @actionnames;
write_unit('DelphiDoom.Keen.ActionIds.pas',
  head('the functions that the states call (think, contact, react)') .
  "unit DelphiDoom.Keen.ActionIds;\n\ninterface\n\nconst\n" . join("\n", @act) .
  "\n  KEEN_ACTION_COUNT = " . ($n) . ";\n\n" .
  "  /// <summary>The name in the C of each action, by id</summary>\n" .
  "  KEEN_ACTION_NAMES: array[0.." . ($n - 1) . "] of string = (\n" . join(",\n", @actnames) . "\n  );\n\nimplementation\n\nend.\n");

# the table of states
my @sid;
for my $i (0 .. $#states) {
  push @sid, sprintf("  KEEN_STATE_%s = %d;", uc($states[$i][0]), $i);
}

sub shape {
  my ($v) = @_;
  return '0' if $v eq 'NULL' || $v eq '0';
  return "KEEN_GFX_$v" if $gfxname{$v};
  return $v if $v =~ /^-?\d+$/;
  return "-1" if $v eq '-1';
  die "unknown shape $v\n";
}

sub number {
  my ($v) = @_;
  return $v if $v =~ /^-?\d+$/;
  die "unknown number $v\n";
}

sub boolean {
  my ($v) = @_;
  return 'True' if $v eq 'true';
  return 'False' if $v eq 'false';
  die "unknown boolean $v\n";
}

sub action {
  my ($v) = @_;
  return 'KEEN_ACTION_NONE' if $v eq 'NULL';
  return 'KEEN_ACTION_' . uc($v);
}

sub nextstate {
  my ($v) = @_;
  return '-1' if $v eq 'NULL' || $v eq '0';
  my $x = $v;
  $x =~ s/^\(.*?\)\s*//;
  $x =~ s/^&//;
  die "unknown next state $v\n" unless exists $stateindex{$x};
  return 'KEEN_STATE_' . uc($x);
}

my @rows;
for my $i (0 .. $#states) {
  my ($name, @f) = @{$states[$i]};
  my %progress = (step => 'kpStep', slide => 'kpSlide', think => 'kpThink', stepthink => 'kpStepThink', slidethink => 'kpSlideThink');
  die "unknown progress $f[2]\n" unless $progress{$f[2]};
  push @rows, sprintf("    (Name: '%s'; LeftShape: %s; RightShape: %s; Progress: %s; Skippable: %s; PushToFloor: %s;\n" .
    "      TicTime: %s; XMove: %s; YMove: %s; Think: %s; Contact: %s; React: %s; NextState: %s)",
    $name, shape($f[0]), shape($f[1]), $progress{$f[2]}, boolean($f[3]), boolean($f[4]), number($f[5]), number($f[6]),
    number($f[7]), action($f[8]), action($f[9]), action($f[10]), nextstate($f[11]));
}

write_unit('DelphiDoom.Keen.StateTable.pas',
  head('the 213 states of the actors (statetype)') .
  "unit DelphiDoom.Keen.StateTable;\n\ninterface\n\nuses\n  DelphiDoom.Keen.GraphicsIds, DelphiDoom.Keen.ActionIds, DelphiDoom.Keen.StateTypes;\n\nconst\n" .
  join("\n", @sid) . "\n  KEEN_STATE_COUNT = " . scalar(@states) . ";\n\n" .
  "  /// <summary>statetype of kd_keen.c, kd_act1.c and kd_act2.c in the order of the files</summary>\n" .
  "  KEEN_STATES: array[0.." . $#states . "] of TKeenStateDef = (\n" . join(",\n", @rows) . "\n  );\n\nimplementation\n\nend.\n");

print "graphics constants: " . scalar(@gfx) . ", sounds: " . scalar(@snd) . ", states: " . scalar(@states) . ", actions: " . scalar(@actionnames) . "\n";
