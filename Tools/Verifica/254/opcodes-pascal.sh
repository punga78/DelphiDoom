#!/bin/sh
# Writes IdTech4/Q3Host/DelphiDoom.Q3Host.Opcodes.pas and DelphiDoom.Q3Host.OpcodeTables.pas from the golden
# Tests/Data/Q3Host/opcodes.golden.txt (the numbers as gcc prints them).
#   opcodes-pascal.sh <repository root>
set -e
ROOT=$1
GOLDEN=$ROOT/Tests/Data/Q3Host/opcodes.golden.txt
DEST=$ROOT/IdTech4/Q3Host
mkdir -p "$DEST"

{
  cat <<'HEAD'
{******************************************************************************}
{                                                                              }
{  DelphiDoom: Quake III host - the numbers of the system calls                 }
{  Based on the Quake III Arena GPL Source Code (id Software)                   }
{                                                                              }
{  Licensed under the GNU General Public License, version 2 or later           }
{                                                                              }
{******************************************************************************}
unit DelphiDoom.Q3Host.Opcodes;

// Generated by Tools\Verifica\254\opcodes-pascal.sh from Tests\Data\Q3Host\opcodes.golden.txt (the values
// gcc prints for the enums of game\g_public.h, cgame\cg_public.h and ui\ui_public.h). Do not edit by hand.

interface

const
HEAD
  awk '{ printf "  %s = %s;\n", $2, $3 }' "$GOLDEN"
  cat <<'TAIL'

implementation

end.
TAIL
} > "$DEST/DelphiDoom.Q3Host.Opcodes.pas"

{
  cat <<'HEAD'
{******************************************************************************}
{                                                                              }
{  DelphiDoom: Quake III host - the names of the system calls                   }
{  Based on the Quake III Arena GPL Source Code (id Software)                   }
{                                                                              }
{  Licensed under the GNU General Public License, version 2 or later           }
{                                                                              }
{******************************************************************************}
unit DelphiDoom.Q3Host.OpcodeTables;

// Generated by Tools\Verifica\254\opcodes-pascal.sh from Tests\Data\Q3Host\opcodes.golden.txt. Do not edit by hand.

interface

uses
  DelphiDoom.Q3Host.Types;

const
HEAD
  for e in gameImport_t gameExport_t cgameImport_t cgameExport_t uiImport_t uiExport_t; do
    # the shared traps (memset ... ceil, qcommon.h) are system calls of game as well
    pat=$e
    if [ $e = gameImport_t ]; then pat="gameImport_t|sharedTraps_t"; fi
    n=$(awk -v e="^($pat)$" '$1 ~ e' "$GOLDEN" | wc -l | tr -d ' ')
    case $e in
      gameImport_t) id=Q3_GAME_IMPORTS ;;
      gameExport_t) id=Q3_GAME_EXPORTS ;;
      cgameImport_t) id=Q3_CGAME_IMPORTS ;;
      cgameExport_t) id=Q3_CGAME_EXPORTS ;;
      uiImport_t) id=Q3_UI_IMPORTS ;;
      uiExport_t) id=Q3_UI_EXPORTS ;;
    esac
    echo "  $id: array[0..$((n - 1))] of TQ3OpcodeEntry = ("
    awk -v e="^($pat)$" -v n=$n '$1 ~ e { c++; printf "    (Name: '"'"'%s'"'"'; Value: %s)%s\n", $2, $3, (c < n ? "," : "") }' "$GOLDEN"
    echo "  );"
    echo
  done
  cat <<'TAIL'
implementation

end.
TAIL
} > "$DEST/DelphiDoom.Q3Host.OpcodeTables.pas"
