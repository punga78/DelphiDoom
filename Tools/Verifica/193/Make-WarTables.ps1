function Rows([string]$Prefix) { $t | Where-Object { $_.StartsWith("$Prefix ") } | ForEach-Object { ,($_.Split(' ')[1..99] | ForEach-Object { [int]$_ }) } }
function Map([string]$Prefix) { ($t | Where-Object { $_.StartsWith("$Prefix ") }).Split(' ')[1..999] | Where-Object { $null -ne $_ } }
function Wrap([string[]]$Values, [int]$Width) {
  $lines = @(); for ($i = 0; $i -lt $Values.Count; $i += $Width) { $lines += '    ' + (($Values[$i..([Math]::Min($i + $Width, $Values.Count) - 1)]) -join ', ') }
  $lines -join (",$nl")
}
