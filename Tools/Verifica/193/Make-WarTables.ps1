function PascalString([string]$Escaped) {
  # $Escaped e' il testo come lo scrive il harness: \n \t \" \\ ; il risultato e' un'espressione Pascal
  $parts = New-Object System.Collections.Generic.List[string]
  $cur = New-Object System.Text.StringBuilder
  $i = 0
  while ($i -lt $Escaped.Length) {
    $c = $Escaped[$i]
    if ($c -eq '\') {
      $n = $Escaped[$i + 1]; $i += 2
      if ($n -eq 'n') { if ($cur.Length) { $parts.Add("'" + $cur.ToString().Replace("'", "''") + "'"); $cur.Clear() | Out-Null }; $parts.Add('#10'); continue }
      if ($n -eq 't') { if ($cur.Length) { $parts.Add("'" + $cur.ToString().Replace("'", "''") + "'"); $cur.Clear() | Out-Null }; $parts.Add('#9'); continue }
      [void]$cur.Append($n); continue
    }
    [void]$cur.Append($c); $i++
  }
  if ($cur.Length) { $parts.Add("'" + $cur.ToString().Replace("'", "''") + "'") }
  if ($parts.Count -eq 0) { return "''" }
  # unisce #10 al pezzo che lo precede
  $out = New-Object System.Collections.Generic.List[string]
  foreach ($p in $parts) {
    if (($p -eq '#10' -or $p -eq '#9') -and $out.Count -gt 0) { $out[$out.Count - 1] = $out[$out.Count - 1] + $p }
    else { $out.Add($p) }
  }
  ($out -join (" +$nl" + '        '))
}

