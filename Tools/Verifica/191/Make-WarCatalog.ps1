param([Parameter(Mandatory)][string]$Catalog, [Parameter(Mandatory)][string]$Out)
$ErrorActionPreference = 'Stop'
$rows = foreach ($l in Get-Content $Catalog) {
  if ($l -match '^C (-?\d+) (\d+) (.*) (\d+) (\d+) (\d+)$') {
    [pscustomobject]@{ Index = [int]$Matches[1]; Type = [int]$Matches[2]; Name = $Matches[3]; P1 = [int]$Matches[4]; P2 = [int]$Matches[5]; P3 = [int]$Matches[6] }
  } else { throw "Riga non valida: $l" }
}
$types = 'wrtUnknown', 'wrtImage', 'wrtPalette', 'wrtXmid', 'wrtCursor', 'wrtUI', 'wrtText', 'wrtLevelInfo', 'wrtLevelVisual', 'wrtLevelPassable', 'wrtSprite', 'wrtWave', 'wrtVoc', 'wrtTileset', 'wrtTiles'
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine(@'
