unit DelphiDoom.War.Catalog.Data;

interface

uses
  DelphiDoom.War.Types;

/// <summary>The entries of the table, in the order of assets[] of the original</summary>
function WarDefaultCatalogEntries: TArray<TWarCatalogEntry>;

implementation

const
'@)
[void]$sb.AppendLine("  CATALOG_COUNT = $($rows.Count);")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('  CATALOG: array[0..CATALOG_COUNT - 1] of TWarCatalogEntry = (')
for ($i = 0; $i -lt $rows.Count; $i++) {
  $r = $rows[$i]; $name = $r.Name.Replace("'", "''")
  $sep = if ($i -lt $rows.Count - 1) { ',' } else { '' }
  [void]$sb.AppendLine(("    (Index: {0}; RecordType: {1}; Name: '{2}'; Param1: {3}; Param2: {4}; Param3: {5}){6}" -f $r.Index, $types[$r.Type], $name, $r.P1, $r.P2, $r.P3, $sep))
}
[void]$sb.AppendLine('  );')
[void]$sb.AppendLine(@'

function WarDefaultCatalogEntries: TArray<TWarCatalogEntry>;
var
  LPosition: Integer;
begin
  SetLength(Result, CATALOG_COUNT);
  for LPosition := 0 to CATALOG_COUNT - 1 do
    Result[LPosition] := CATALOG[LPosition];
end;

end.
'@)
[IO.File]::WriteAllText($Out, $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object Text.UTF8Encoding($true)))
"Scritto $Out ($($rows.Count) voci, indici distinti: $(($rows | Select-Object -Unique Index | Measure-Object).Count))"
