<#
  Issue #192: genera Libs\War\DelphiDoom.War.Font.Data.pas dall'uscita del C ORIGINALE
  (war_gfx_ref.exe - fonts, cioe' la tabella fontsData[2] di war_font.c stampata dal programma compilato).
  Non si modifica a mano il file generato: si rifa con questo script.

  Uso:  powershell -NoProfile -File Make-WarFonts.ps1 -Fonts Tests\Data\War\fonts.golden.txt -Out Libs\War\DelphiDoom.War.Font.Data.pas
#>
param(
  [Parameter(Mandatory)][string]$Fonts,
  [Parameter(Mandatory)][string]$Out
)
$ErrorActionPreference = 'Stop'
$lines = Get-Content $Fonts | Where-Object { $_ -ne '' }
$heads = @{}
$glyphs = @{}
foreach ($l in $lines) {
  $p = $l -split ' '
  if ($p[0] -eq 'F') { $heads[[int]$p[1]] = $p[2..5] }
  elseif ($p[0] -eq 'G') {
    $f = [int]$p[1]
    if (-not $glyphs.ContainsKey($f)) { $glyphs[$f] = @() }
    $glyphs[$f] += , @($p[3], $p[4], $p[5], $p[6])
  }
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('{******************************************************************************}')
[void]$sb.AppendLine('{                                                                              }')
[void]$sb.AppendLine('{  DelphiDoom: war library - the glyph tables of the two fonts                 }')
[void]$sb.AppendLine('{                                                                              }')
[void]$sb.AppendLine('{  Generated by Tools\Verifica\192\Make-WarFonts.ps1 from the table fontsData[] }')
[void]$sb.AppendLine('{  of war_font.c of war1 (acoto87/war1), compiled and printed by the original   }')
[void]$sb.AppendLine('{  C code: do not edit by hand                                                  }')
[void]$sb.AppendLine('{                                                                              }')
[void]$sb.AppendLine('{  Port of war1 (c) 2019 Alejandro Coto Gutierrez, zlib License (see           }')
[void]$sb.AppendLine('{  Libs\War\LICENSE-war1.txt). This is an altered version, not the original.   }')
[void]$sb.AppendLine('{                                                                              }')
[void]$sb.AppendLine('{  Licensed under the GNU General Public License, version 2 or later           }')
[void]$sb.AppendLine('{                                                                              }')
[void]$sb.AppendLine('{******************************************************************************}')
[void]$sb.AppendLine('unit DelphiDoom.War.Font.Data;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('interface')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('uses')
[void]$sb.AppendLine('  DelphiDoom.War.Font.Types;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// <summary>The font AFont (0 = in game texts, 1 = menu texts) of the table fontsData[] of the original</summary>')
[void]$sb.AppendLine('function WarDefaultFontData(AFont: Integer): TWarFontData;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('implementation')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const')
foreach ($f in 0, 1) {
  $h = $heads[$f]
  [void]$sb.AppendLine("  FONT$f`_GLYPHS: TWarGlyphTable = (")
  $rows = @()
  foreach ($g in $glyphs[$f]) { $rows += "    (X: $($g[0]); Y: $($g[1]); Width: $($g[2]); Height: $($g[3]))" }
  [void]$sb.AppendLine(($rows -join ",`r`n"))
  [void]$sb.AppendLine('  );')
  [void]$sb.AppendLine('')
}
[void]$sb.AppendLine('function WarDefaultFontData(AFont: Integer): TWarFontData;')
[void]$sb.AppendLine('begin')
[void]$sb.AppendLine('  case AFont of')
foreach ($f in 0, 1) {
  $h = $heads[$f]
  [void]$sb.AppendLine("    $f`:")
  [void]$sb.AppendLine('      begin')
  [void]$sb.AppendLine("        Result.SpriteWidth := $($h[0]);")
  [void]$sb.AppendLine("        Result.SpriteHeight := $($h[1]);")
  [void]$sb.AppendLine("        Result.LineHeight := $($h[2]);")
  [void]$sb.AppendLine("        Result.Advance := $($h[3]);")
  [void]$sb.AppendLine("        Result.Glyphs := FONT$f`_GLYPHS;")
  [void]$sb.AppendLine('      end;')
}
[void]$sb.AppendLine('  else')
[void]$sb.AppendLine('    Result := Default(TWarFontData);')
[void]$sb.AppendLine('  end;')
[void]$sb.AppendLine('end;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('end.')
$text = ($sb.ToString() -replace "`r`n", "`n") -replace "`n", "`r`n"
[IO.File]::WriteAllText($Out, $text, (New-Object System.Text.UTF8Encoding($false)))
